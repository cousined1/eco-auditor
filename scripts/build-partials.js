/**
 * build-partials.js — CTA-slot design authority + Header component generator.
 *
 * This file is the **single source of truth** for the shared header partial
 * pattern. It defines every header variant, its nav items, and most importantly
 * its CTA slot contract. Run it to regenerate src/components/Header.tsx.
 *
 * ─── CTA Slot Contract ─────────────────────────────────────────────────
 *
 * Every header variant exposes a `cta` prop slot that accepts an array of
 * CTA action descriptors. Each action has:
 *
 *   { label, href, variant?: 'primary' | 'secondary' | 'icon' }
 *
 * If no `cta` prop is passed, the variant's **default CTA** is used.
 * Pass an empty array `cta={[]}` to hide CTAs entirely.
 *
 * ─── Variants ───────────────────────────────────────────────────────────
 *
 *   Variant     | Default CTA                    | Use case
 *   ────────────|────────────────────────────────┼──────────────────────
 *   landing     | [Login (secondary),            | Landing page hero
 *               |  Start Free Trial (primary)]   |
 *   marketing   | [Start Free Trial (primary),   | /methodology,
 *               |  Book a Demo (secondary)]      | /sample-report,
 *                                               | /security
 *   legal       | [] (none)                      | /privacy, /terms,
 *                                               | /dpa, /contact
 *   app         | [Notifications (icon),         | /app/* (authenticated)
 *               |  User avatar]                  |
 *
 * ─── Usage ──────────────────────────────────────────────────────────────
 *
 *   node scripts/build-partials.js
 *
 *   Generates src/components/Header.tsx with full TypeScript types.
 *   The generated file is self-contained and ready for import.
 */

// ---------------------------------------------------------------------------
// 1. Config — each variant's defaults
// ---------------------------------------------------------------------------

/** @typedef {'primary'|'secondary'|'icon'} CtaVariant */

/**
 * @typedef {{ label: string; href?: string; onClick?: string; variant?: CtaVariant; icon?: string }} CtaAction
 */

/**
 * @typedef {'landing'|'marketing'|'legal'|'app'} HeaderVariant
 */

/**
 * @typedef {{ nav: Array<{ label: string; href: string; isHash?: boolean }>; cta: CtaAction[]; sticky: boolean; themeToggle: boolean }} VariantConfig
 */

/** @type {Record<HeaderVariant, VariantConfig>} */
const VARIANTS = {
  landing: {
    nav: [
      { label: 'Features', href: '#features', isHash: true },
      { label: 'How It Works', href: '#how-it-works', isHash: true },
      { label: 'Pricing', href: '/pricing' },
      { label: 'Methodology', href: '/methodology' },
      { label: 'Security', href: '/security' },
    ],
    cta: [
      { label: 'Log In', href: '/login', variant: 'secondary' },
      { label: 'Start Free Trial', href: '/signup', variant: 'primary' },
    ],
    sticky: true,
    themeToggle: true,
  },

  marketing: {
    nav: [
      { label: 'Features', href: '/#features', isHash: true },
      { label: 'Pricing', href: '/pricing' },
      { label: 'Methodology', href: '/methodology' },
      { label: 'Sample Report', href: '/sample-report' },
      { label: 'Security', href: '/security' },
    ],
    cta: [
      { label: 'Start Free Trial', href: '/signup', variant: 'primary' },
      { label: 'Book a Demo', href: '/contact', variant: 'secondary' },
    ],
    sticky: true,
    themeToggle: true,
  },

  legal: {
    nav: [],
    cta: [],
    sticky: false,
    themeToggle: true,
  },

  app: {
    nav: [],
    cta: [
      { label: 'Notifications', icon: 'BellIcon', variant: 'icon' },
    ],
    sticky: false,
    themeToggle: true,
  },
};

// ---------------------------------------------------------------------------
// 2. Generator — writes src/components/Header.tsx
// ---------------------------------------------------------------------------

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '..', 'src', 'components', 'Header.tsx');

function generate() {
  const lines = [];

  lines.push(`// Auto-generated by scripts/build-partials.js — DO NOT EDIT DIRECTLY`);
  lines.push(`// Run \`node scripts/build-partials.js\` to regenerate.`);
  lines.push(`//`);
  lines.push(`// CTA Slot Contract:`);
  lines.push(`//   cta prop accepts CtaAction[] with { label, href, variant?, icon? }`);
  lines.push(`//   Empty array hides CTAs. Omitted prop uses variant default.`);
  lines.push(``);
  lines.push(`import { Link } from 'react-router-dom';`);
  lines.push(`import type { ReactNode } from 'react';`);
  lines.push(``);
  lines.push(`// ─── Types ────────────────────────────────────────────────────`);
  lines.push(``);
  lines.push(`export type CtaVariant = 'primary' | 'secondary' | 'icon';`);
  lines.push(``);
  lines.push(`export interface CtaAction {`);
  lines.push(`  label: string;`);
  lines.push(`  href?: string;`);
  lines.push(`  onClick?: () => void;`);
  lines.push(`  variant?: CtaVariant;`);
  lines.push(`  icon?: ReactNode;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export type HeaderVariant = ${Object.keys(VARIANTS).map(v => `'${v}'`).join(' | ')};`);
  lines.push(``);
  lines.push(`export interface HeaderProps {`);
  lines.push(`  /** Determines default nav items and default CTA */`);
  lines.push(`  variant: HeaderVariant;`);
  lines.push(`  /** Override default CTAs. Pass [] to hide. */`);
  lines.push(`  cta?: CtaAction[];`);
  lines.push(`  /** Override default nav items */`);
  lines.push(`  navItems?: Array<{ label: string; href: string }>;`);
  lines.push(`  /** Suppress the entire CTA area (shortcut for cta=[]) */`);
  lines.push(`  hideCta?: boolean;`);
  lines.push(`  /** Extra elements after nav (e.g. theme toggle) */`);
  lines.push(`  extra?: ReactNode;`);
  lines.push(`  className?: string;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`// ─── Icon components (inline SVGs) ──────────────────────────`);
  lines.push(``);
  lines.push(`function BellIcon({ className }: { className?: string }) {`);
  lines.push(`  return (`);
  lines.push(`    <svg className={className ?? 'w-5 h-5'} viewBox="0 0 20 20" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round">`);
  lines.push(`      <path d="M10 2a6 6 0 00-6 6v3l-1 3h14l-1-3V8a6 6 0 00-6-6z"/>`);
  lines.push(`      <path d="M7.5 14a2.5 2.5 0 005 0"/>`);
  lines.push(`    </svg>`);
  lines.push(`  );`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`function EcoLogo() {`);
  lines.push(`  return (`);
  lines.push(`    <svg className="w-7 h-7" viewBox="0 0 28 28" fill="none" xmlns="http://www.w3.org/2000/svg" aria-label="Eco-Auditor logo">`);
  lines.push(`      <rect width="28" height="28" rx="7" fill="currentColor" className="text-brand-600"/>`);
  lines.push(`      <path d="M8 20V8l6 4 6-4v12" stroke="white" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>`);
  lines.push(`    </svg>`);
  lines.push(`  );`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`// ─── Variant defaults ───────────────────────────────────────`);
  lines.push(``);

  // Emit DEFAULT_NAV
  lines.push(`const DEFAULT_NAV: Record<HeaderVariant, Array<{ label: string; href: string }>> = {`);
  for (const [v, cfg] of Object.entries(VARIANTS)) {
    lines.push(`  ${v}: [`);
    for (const item of cfg.nav) {
      lines.push(`    { label: '${item.label}', href: '${item.href}' },`);
    }
    lines.push(`  ],`);
  }
  lines.push(`};`);
  lines.push(``);

  // Emit DEFAULT_CTA
  lines.push(`const DEFAULT_CTA: Record<HeaderVariant, CtaAction[]> = {`);
  for (const [v, cfg] of Object.entries(VARIANTS)) {
    lines.push(`  ${v}: [`);
    for (const a of cfg.cta) {
      if (a.variant === 'icon') {
        lines.push(`    { label: '${a.label}', icon: <BellIcon />, variant: 'icon' },`);
      } else {
        lines.push(`    { label: '${a.label}', href: '${a.href}', variant: '${a.variant}' },`);
      }
    }
    lines.push(`  ],`);
  }
  lines.push(`};`);
  lines.push(``);

  lines.push(`const STICKY: Record<HeaderVariant, boolean> = {`);
  for (const [v, cfg] of Object.entries(VARIANTS)) {
    lines.push(`  ${v}: ${cfg.sticky},`);
  }
  lines.push(`};`);
  lines.push(``);

  // ─── Component ────────────────────────────────────────────────────
  lines.push(`// ─── Component ───────────────────────────────────────────────`);
  lines.push(``);
  lines.push(`export default function Header({ variant, cta, navItems, hideCta, extra, className }: HeaderProps) {`);
  lines.push(`  const resolvedNav = navItems ?? DEFAULT_NAV[variant];`);
  lines.push(`  const resolvedCta = hideCta ? [] : (cta ?? DEFAULT_CTA[variant]);`);
  lines.push(`  const isSticky = STICKY[variant];`);
  lines.push(``);
  lines.push(`  return (`);
  lines.push(`    <header`);
  lines.push(`      className={\`\${isSticky ? 'sticky top-0 ' : ''}z-50 border-b border-surface-200/80 dark:border-surface-800/80 bg-white/90 dark:bg-surface-900/90 backdrop-blur-md\${className ? ' ' + className : ''}\`}>`);
  lines.push(`      <div className="max-w-7xl mx-auto px-6 py-3 flex items-center justify-between">`);
  lines.push(`        {/* Logo */}`);
  lines.push(`        <Link to="/" className="flex items-center gap-2.5">`);
  lines.push(`          <EcoLogo />`);
  lines.push(`          <span className="font-semibold text-sm text-surface-900 dark:text-white tracking-tight">Eco-Auditor</span>`);
  lines.push(`        </Link>`);
  lines.push(``);
  lines.push(`        {/* Nav items */}`);
  lines.push(`        {resolvedNav.length > 0 && (`);
  lines.push(`          <nav className="hidden md:flex items-center gap-6 text-sm" aria-label="Main navigation">`);
  lines.push(`            {resolvedNav.map((item) => (`);
  lines.push(`              item.href.startsWith('#') ? (`);
  lines.push(`                <a key={item.href} href={item.href} className="inline-flex items-center no-underline text-surface-600 dark:text-surface-400 hover:text-surface-900 dark:hover:text-white transition-colors">{item.label}</a>`);
  lines.push(`              ) : (`);
  lines.push(`                <Link key={item.href} to={item.href} className="inline-flex items-center no-underline text-surface-600 dark:text-surface-400 hover:text-surface-900 dark:hover:text-white transition-colors">{item.label}</Link>`);
  lines.push(`              )`);
  lines.push(`            ))}`);
  lines.push(`          </nav>`);
  lines.push(`        )}`);
  lines.push(``);
  lines.push(`        {/* CTA slot + extras */}`);
  lines.push(`        <div className="flex items-center gap-3">`);
  lines.push(`          {extra}`);
  lines.push(`          {resolvedCta.map((action, i) => {`);
  lines.push(`            const key = action.href ?? action.label;`);
  lines.push(`            if (action.variant === 'icon') {`);
  lines.push(`              return (`);
  lines.push(`                <button key={key} type="button" onClick={action.onClick} className="relative p-1.5 rounded-lg hover:bg-surface-100 dark:hover:bg-surface-800 text-surface-500 transition-colors" aria-label={action.label}>`);
  lines.push(`                  {action.icon}`);
  lines.push(`                </button>`);
  lines.push(`              );`);
  lines.push(`            }`);
  lines.push(`            if (action.variant === 'secondary' || (resolvedCta.length > 1 && i < resolvedCta.length - 1)) {`);
  lines.push(`              return (`);
  lines.push(`                <Link key={key} to={action.href ?? '#'} onClick={action.onClick as any} className="btn-secondary text-sm !py-2 !px-5">{action.label}</Link>`);
  lines.push(`              );`);
  lines.push(`            }`);
  lines.push(`            return (`);
  lines.push(`              <Link key={key} to={action.href ?? '#'} onClick={action.onClick as any} className="btn-primary text-sm !py-2 !px-5">{action.label}</Link>`);
  lines.push(`            );`);
  lines.push(`          })}`);
  lines.push(`        </div>`);
  lines.push(`      </div>`);
  lines.push(`    </header>`);
  lines.push(`  );`);
  lines.push(`}`);
  lines.push(``);

  const code = lines.join('\n');
  writeFileSync(OUT, code, 'utf-8');
  console.log(`✓ Wrote ${OUT}`);
  console.log(`  Variants: ${Object.keys(VARIANTS).join(', ')}`);
  console.log(`  Total configs: ${Object.keys(VARIANTS).length}`);
}

// ---------------------------------------------------------------------------
// 3. Export config for consumers (design authority)
// ---------------------------------------------------------------------------

export { VARIANTS, generate };
export default generate;

// Run directly
if (process.argv[1] && import.meta.url.startsWith('file:')) {
  const run = resolve(process.argv[1]);
  if (run === resolve(fileURLToPath(import.meta.url))) {
    generate();
  }
}
